String tx(BuildContext context, String hu) {
  final language = AppScope.of(context).language;
  if (language == AppLanguage.hungarian) return hu;
  return _translations[language]?[hu] ??
      _recipeTextTranslations[language]?[hu] ??
      _recipeStepTranslations[language]?[hu] ??
      _recipeStepTranslations[AppLanguage.english]?[hu] ??
      hu;
}

String txBmiCategory(BuildContext context, String category) =>
    switch (category) {
      'Sovány' => tx(context, 'Sovány'),
      'Normál súly' => tx(context, 'Normál súly'),
      'Túlsúlyos' => tx(context, 'Túlsúlyos'),
      'Obezitás' => tx(context, 'Obezitás'),
      _ => category,
    };

